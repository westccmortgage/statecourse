import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getCourseConfiguration, getCourseDelivery } from '../config/course-registry.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const courseId = 'ca-mortgage-loan-brokering-lending-45';
const course = getCourseConfiguration(courseId);
const metrics = {};

function sliceSource(lines, range) {
  if (!range) return '';
  const find = (heading) => heading === '^' ? 0 : heading === '$' ? lines.length
    : lines.findIndex((line) => line.trim() === heading);
  const start = find(range.from), end = find(range.to);
  return start >= 0 && end > start ? lines.slice(start, end).join('\n') : '';
}

function countWords(text) {
  return (text.match(/[A-Za-z0-9][A-Za-z0-9’'/-]*/g) || []).length;
}

function countLines(text) {
  return text.split('\n').filter((line) => line.trim() && !/^#{1,6}\s/.test(line.trim())).length;
}

for (const assignment of course.assignments) {
  const lessonNumber = String(assignment.sequence).padStart(2, '0');
  const sourcePath = path.join(root, 'california/ca-mortgage-loan-brokering-lending-45-v1/curriculum', `lesson-${lessonNumber}.md`);
  const sourceLines = fs.readFileSync(sourcePath, 'utf8').replace(/\r/g, '').split('\n');
  const delivery = getCourseDelivery(courseId, assignment.id);
  for (const block of delivery.blocks) {
    for (const screen of block.screens) {
      if (screen.type === 'completion') continue;
      const text = typeof screen.bodyMarkdown === 'string' ? screen.bodyMarkdown : sliceSource(sourceLines, screen.content);
      metrics[screen.id] = { lines: countLines(text), words: countWords(text) };
    }
  }
}

const target = path.join(root, 'config/california/mortgage-screen-study-metrics.mjs');
const source = `/* Generated by scripts/generate-mortgage-screen-study-metrics.mjs. */\n`
  + `export const MORTGAGE_SCREEN_STUDY_METRICS = Object.freeze(${JSON.stringify(metrics, null, 2)});\n`;
fs.writeFileSync(target, source);
console.log(JSON.stringify({ target: path.relative(root, target), screens: Object.keys(metrics).length }));
