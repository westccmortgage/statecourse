import fs from "node:fs";
import { parseModule as parseLegacyModule } from "./generate-tx-block-maps.mjs";

export function parseModule(markdown, unitCodes) {
  let index = 0;
  const originalHeadings = new Map();
  const titles = new Map();
  const normalized = markdown.replace(/^## (T\d{2}U\d+) [—–-] (.+)$/gm, (heading, code, title) => {
    if (code !== unitCodes[index++]) throw new Error(`module: unit ${code} is out of order`);
    // Codes keep equal official titles distinct (e.g. multiple Case Study/Workshop units).
    const alias = `## Unit: ${code} — ${title}`;
    originalHeadings.set(alias, heading);
    titles.set(code, title);
    return alias;
  });
  if (index && index !== unitCodes.length) throw new Error("module: mixed or incomplete coded unit headings");
  const parsed = parseLegacyModule(normalized, unitCodes);
  for (const block of parsed.blocks) {
    block.title = titles.get(block.code) ?? block.title;
    for (const screen of block.screens) {
      if (screen.type === "instruction") screen.title = block.title;
      if (screen.from) screen.from = originalHeadings.get(screen.from) ?? screen.from;
      if (screen.to) screen.to = originalHeadings.get(screen.to) ?? screen.to;
    }
  }
  return parsed;
}

export function generateModuleBlocks(course, moduleNumber) {
  const nn = String(moduleNumber).padStart(2, "0");
  const markdown = fs.readFileSync(`${course.curriculumDir}/module-${nn}.md`, "utf8");
  const { blocks, recapMark, optionalMark } = parseModule(markdown, course.unitCodes);
  const mapped = blocks.map((block, index) => {
    const learningObjective = course.unitObjectives[block.code];
    if (!learningObjective?.trim()) throw new Error(`No learning objective for ${block.code}`);
    return { id: block.id, sequence: index + 1, required: true, code: block.code, title: block.title, learningObjective,
      screens: block.screens.map((screen, position) => ({ id: `${block.id}-s${position + 1}`, sequence: position + 1,
        type: screen.type, title: screen.title,
        ...(screen.type === "retrieval" ? { questionId: screen.questionId } : { content: { from: screen.from, to: screen.to } }) })) };
  });
  mapped.push({ id: `t${moduleNumber}-recap`, sequence: mapped.length + 1, required: true, title: "Module recap",
    screens: [{ id: `t${moduleNumber}-recap-s1`, sequence: 1, type: "review", title: "Module recap",
      content: { from: recapMark.heading, to: optionalMark?.heading ?? "$" } }] });
  if (optionalMark) mapped.push({ id: `t${moduleNumber}-optional`, sequence: mapped.length + 1,
    required: false, optional: true, nonBlocking: true, excludedFromRequiredTime: true, noAssessmentMayDependOnThis: true,
    title: optionalMark.title, screens: [{ id: `t${moduleNumber}-optional-s1`, sequence: 1, type: "optional-reference",
      title: optionalMark.title, content: { from: optionalMark.heading, to: "$" } }] });
  const object = { courseId: course.courseId, moduleId: `module-${nn}`, version: "1.0",
    contentPath: `/content/texas/${course.courseId}/module-${nn}.md`, blocks: mapped };
  const output = `/** Generated by scripts/lib/generate-complete-tx-block-maps.mjs from this course's actual required units. */\n`
    + `export const MODULE_${moduleNumber}_BLOCKS = Object.freeze(${JSON.stringify(object, null, 2)});\n`
    + `export default MODULE_${moduleNumber}_BLOCKS;\n`;
  fs.writeFileSync(course.outFile(moduleNumber), output);
  return course.outFile(moduleNumber);
}
